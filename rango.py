
# 10. Número Dentro de Rango
# Pide un número al usuario. Di si está dentro del rango de 1 a 10 (inclusive).


numero = float(input("Ingrese un número: "))

if 1 <= numero <= 10:
        print(f"El número {numero} está dentro del rango de 1 a 10.")
else:

     print(f"El número {numero} está fuera del rango de 1 a 10.")
